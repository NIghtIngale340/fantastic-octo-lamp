#!/usr/bin/env python3
"""Regenerate docs/coverage.md by mapping every scoreboard solve to its writeup.

Source of truth is data/solved-list.txt (category|challenge|points per line),
exported from the PCGCTF scoreboard. Challenge IDs come from
data/challenges.json; the Juice Shop inventory under data/juice-shop/ supplies
IDs for challenges the main snapshot missed.

Usage:  python scripts/audit_coverage.py [--check]

--check exits non-zero if coverage changed since docs/coverage.md was written,
so CI can catch a new solve that nobody wrote up.
"""
import collections
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JOKE_POINTS = 20000  # the single 20,000-point challenge skews every total


def norm(s):
    s = s.lower().replace("—", "-").replace("–", "-").replace("’", "'")
    return re.sub(r"[^a-z0-9]+", "", s)


def load_challenge_index():
    """Map normalized challenge name -> id, across every inventory we hold."""
    index = {}
    with open(os.path.join(ROOT, "data", "challenges.json"), encoding="utf-8") as fh:
        for c in json.load(fh):
            index.setdefault(norm(c["name"]), c["id"])
    for path in glob.glob(os.path.join(ROOT, "data", "juice-shop", "live-inventory-*.json")):
        with open(path, encoding="utf-8") as fh:
            try:
                blob = json.load(fh)
            except ValueError:
                continue
        items = blob if isinstance(blob, list) else blob.get("challenges", blob.get("data", []))
        if isinstance(items, list):
            for c in items:
                if isinstance(c, dict) and "name" in c and "id" in c:
                    index.setdefault(norm(c["name"]), c["id"])
    return index


def load_writeup_index():
    """Map both challenge id and normalized title -> writeup paths."""
    by_id, by_title, by_heading = {}, {}, {}
    for path in glob.glob(os.path.join(ROOT, "writeups", "*", "*.md")):
        rel = os.path.relpath(path, ROOT).replace(os.sep, "/")
        base = os.path.basename(path)
        m = re.match(r"^(\d+)-", base)
        if m:
            by_id.setdefault(int(m.group(1)), []).append(rel)
        by_title.setdefault(norm(os.path.splitext(base)[0]), []).append(rel)
        # A few drafts cover several challenges under their own headings.
        with open(path, encoding="utf-8", errors="replace") as fh:
            text = fh.read()
        for heading in re.findall(r"^#{2,3}\s+(.+)$", text, re.M):
            heading = re.sub(r"\s*[-—]\s*\d+\s*(pts|points).*$", "", heading.strip(), flags=re.I)
            heading = re.sub(r"^\d+\.\s*", "", heading)
            by_heading.setdefault(norm(heading), set()).add(rel)
    return by_id, by_title, by_heading


def build_rows():
    ids = load_challenge_index()
    by_id, by_title, by_heading = load_writeup_index()
    rows = []
    with open(os.path.join(ROOT, "data", "solved-list.txt"), encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            category, name, points = line.split("|")
            key = norm(name)
            cid = ids.get(key)
            files = by_id.get(cid, []) if cid is not None else []
            if not files:
                files = by_title.get(key, [])
            if not files:
                files = sorted(by_heading.get(key, []))
            rows.append({"cat": category, "name": name, "pts": int(points),
                         "cid": cid, "files": files})
    return rows


def render(rows):
    documented = [r for r in rows if r["files"]]
    missing = [r for r in rows if not r["files"]]
    points = sum(r["pts"] for r in rows)
    points_core = sum(r["pts"] for r in rows if r["pts"] < JOKE_POINTS)
    totals = collections.Counter(r["cat"] for r in rows)
    gaps = collections.Counter(r["cat"] for r in missing)

    out = [
        "# Writeup coverage audit",
        "",
        "Generated by `scripts/audit_coverage.py`. Do not edit by hand.",
        "",
        f"- **Solved problems listed:** {len(rows)}",
        f"- **Covered by a writeup:** {len(documented)}",
        f"- **No writeup:** {len(missing)}",
        f"- **Points represented:** {points:,} ({points_core:,} excluding the "
        f"{JOKE_POINTS:,}-point outlier)",
        "",
        "Coverage means a draft exists for that challenge. It is not a claim of platform",
        "acceptance: each draft states its own verification status, and several record an",
        "evidence-backed answer whose submission was never confirmed.",
        "",
        "## Gaps",
        "",
        "| Category | Challenge | Points | Why it is missing |",
        "| --- | --- | ---: | --- |",
    ]
    for r in missing:
        reason = ("Added to the scoreboard after the 28 October inventory snapshot, so no "
                  "challenge folder or draft was ever created"
                  if r["cid"] is None else
                  "Juice Shop track; solved against the live instance but never drafted")
        out.append(f"| {r['cat']} | {r['name']} | {r['pts']} | {reason} |")
    out += [
        "",
        "The OSINT / IMINT gaps occupy challenge IDs the snapshot skipped "
        "(245, 246, 248, 249, 255, 257).",
        "",
        "## Coverage by category",
        "",
        "| Category | Solved | Documented | Missing |",
        "| --- | ---: | ---: | ---: |",
    ]
    for cat, n in totals.most_common():
        gap = gaps.get(cat, 0)
        out.append(f"| {cat} | {n} | {n - gap} | {gap if gap else '—'} |")
    out += [
        f"| **Total** | **{len(rows)}** | **{len(documented)}** | **{len(missing)}** |",
        "",
        "## Full map",
        "",
        "| Category | Challenge | Points | Writeup |",
        "| --- | --- | ---: | --- |",
    ]
    for r in rows:
        links = (" · ".join(f"[{os.path.basename(f)}](../{f})" for f in r["files"])
                 if r["files"] else "**none**")
        out.append(f"| {r['cat']} | {r['name']} | {r['pts']} | {links} |")
    out.append("")
    return "\n".join(out)


def main():
    rows = build_rows()
    text = render(rows)
    target = os.path.join(ROOT, "docs", "coverage.md")
    missing = sum(1 for r in rows if not r["files"])

    if "--check" in sys.argv:
        current = ""
        if os.path.exists(target):
            with open(target, encoding="utf-8") as fh:
                current = fh.read()
        if current != text:
            print("docs/coverage.md is stale; run: python scripts/audit_coverage.py")
            return 1
        print(f"coverage up to date: {len(rows)} solves, {missing} undocumented")
        return 0

    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote docs/coverage.md: {len(rows)} solves, "
          f"{len(rows) - missing} documented, {missing} undocumented")
    return 0


if __name__ == "__main__":
    sys.exit(main())
